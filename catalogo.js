window.getProduct = function getProduct(productId) {
  return window.CATALOG.find((product) => product.id === productId);
};

function numberWithin(value, fallback, minimum, maximum) {
  const number = Number(value);
  return Number.isFinite(number) ? Math.min(maximum, Math.max(minimum, number)) : fallback;
}

window.setCatalog = function setCatalog(products) {
  if (!Array.isArray(products)) return;
  window.CATALOG = products.map((product) => ({
    ...product,
    active: product.active !== false,
    quantity: Number.isFinite(Number(product.quantity)) ? Number(product.quantity) : 0,
    price: Number.isFinite(Number(product.price)) ? Number(product.price) : 0,
    imageZoom: numberWithin(product.imageZoom, 1, 1, 2.4),
    imageX: numberWithin(product.imageX, 0, -50, 50),
    imageY: numberWithin(product.imageY, 0, -50, 50),
  }));
};

window.productImageStyle = function productImageStyle(product) {
  const zoom = numberWithin(product?.imageZoom, 1, 1, 2.4);
  const x = numberWithin(product?.imageX, 0, -50, 50);
  const y = numberWithin(product?.imageY, 0, -50, 50);
  return `--image-zoom:${zoom};--image-x:${x}%;--image-y:${y}%`;
};

window.categoryLabel = function categoryLabel(categoryId) {
  return window.CATEGORIES.find((category) => category.id === categoryId)?.label || categoryId;
};
